#!/usr/bin/env node
/**
 * `content/field-guide.json` — the player-facing projection of canon's lore.
 *
 * Canon is written for whoever runs the game, so it carries things a player
 * must never read: `hidden_truths`, `canon_constraints`, `common_story_uses`,
 * the generator's `agent_instructions`. The field guide is what is left when
 * every field has to be named to get through. It is generated, never edited:
 * `npm run canon:field-guide` after any change to canon's lore, exactly like
 * the bestiary.
 *
 * The allow-list lives in `field-guide-build.ts` as plain property copies, so a
 * new canon field stays private until somebody writes it in. Keyed by canon id
 * (`creature.embermoth`) because that is what a chapter's `discovers` list and
 * every `likes` edge already say.
 *
 * Entities with no `lore` block still get an entry — a creature you can meet is
 * in the guide whether or not anyone has written its story yet — and are listed
 * below so the gaps are visible. Opinions that point at something outside the
 * guide (a faction with no lore, say) are listed too: the client must not link
 * to a page that is not there.
 */

import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { loadCanon } from "@kad/canon";
import { buildFieldGuide } from "./field-guide-build.ts";

const ROOT = path.resolve(import.meta.dirname, "..", "..");
const OUT = path.join(ROOT, "content", "field-guide.json");
const ASSETS = path.join(ROOT, "assets");

const registry = loadCanon(path.join(ROOT, "canon"));
const { guide, report } = buildFieldGuide(registry, (rel) => fs.existsSync(path.join(ASSETS, rel)));

const doc = {
  $comment:
    "GENERATED by tools/canon/field-guide.ts from canon/*.yaml — do not edit. " +
    "Canon is the source of truth (docs/canon-contract.md); run `npm run canon:field-guide`.",
  ...guide,
};

fs.writeFileSync(OUT, `${JSON.stringify(doc, null, 2)}\n`);

const counts = new Map<string, number>();
for (const entry of Object.values(guide.entries)) {
  counts.set(entry.category, (counts.get(entry.category) ?? 0) + 1);
}
console.log(
  `${path.relative(ROOT, OUT)} — ${Object.keys(guide.entries).length} entries (` +
    `${[...counts].map(([category, n]) => `${n} ${category}`).join(", ")})`,
);
if (report.withoutLore.length > 0) {
  console.log(`  no lore yet (${report.withoutLore.length}): ${report.withoutLore.join(", ")}`);
}
for (const { from, field, to } of report.unresolved) {
  console.log(`  unresolved: ${from} ${field} -> ${to} (not in the guide)`);
}
process.exitCode = 0;
