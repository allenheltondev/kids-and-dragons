#!/usr/bin/env node
/**
 * `content/world.json` — where every place is, projected from canon.
 *
 * Canon owns the geography: `biomes.yaml` and `locations.yaml` each carry a
 * `map_anchor` in geography.yaml's normalized 1000×1000 frame, traced from the
 * realm painting (`art/reference/realm_of_red_sky.png`). The phone's world map
 * draws the party standing on the anchor of the chapter's `biome`, and that is
 * all it needs from canon: a title and two numbers per place.
 *
 * Generated, never edited: `npm run canon:world`. The client cannot read canon
 * directly — `@kad/canon` carries Zod and the YAML, neither of which belongs
 * in a phone's bundle — so this is the projection it reads instead, served
 * statically beside the chapters.
 *
 * Keyed by slug (the id after `biome.` / `location.`), because that is what a
 * chapter's `biome` field already says: `exchange`, `sunward_fields`,
 * `mount_red_sky`. A place canon has not put on the map (no `map_anchor`) is
 * left out rather than guessed at — the map shows nothing for it, which is
 * honest, where an invented anchor would put the party in the sea.
 */

import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { loadCanon, slugOf } from "@kad/canon";
import type { WorldMap, WorldPlace } from "@kad/shared";

const ROOT = path.resolve(import.meta.dirname, "..", "..");
const OUT = path.join(ROOT, "content", "world.json");
const IMAGE = path.join(ROOT, "assets", "world", "realm_of_red_sky.webp");

/** The shipped painting's pixel size, read off the file so the two cannot drift. */
function webpSize(file: string): { width: number; height: number } {
  const buf = fs.readFileSync(file);
  // RIFF....WEBPVP8X: the extended header carries the canvas size minus one,
  // 24 bits each, little-endian, at offsets 24 and 27.
  if (buf.toString("ascii", 0, 4) !== "RIFF" || buf.toString("ascii", 8, 12) !== "WEBP") {
    throw new Error(`${file} is not a WebP`);
  }
  const chunk = buf.toString("ascii", 12, 16);
  if (chunk === "VP8X") {
    return {
      width: 1 + (buf[24]! | (buf[25]! << 8) | (buf[26]! << 16)),
      height: 1 + (buf[27]! | (buf[28]! << 8) | (buf[29]! << 16)),
    };
  }
  if (chunk === "VP8 ") {
    return { width: buf.readUInt16LE(26) & 0x3fff, height: buf.readUInt16LE(28) & 0x3fff };
  }
  if (chunk === "VP8L") {
    const bits = buf.readUInt32LE(21);
    return { width: 1 + (bits & 0x3fff), height: 1 + ((bits >> 14) & 0x3fff) };
  }
  throw new Error(`${file}: unknown WebP chunk ${chunk}`);
}

interface Anchored {
  id: string;
  title: string;
  map_anchor?: { x: number; y: number };
  parent_biome?: string;
}

const registry = loadCanon(path.join(ROOT, "canon"));
const places: Record<string, WorldPlace> = {};
const problems: string[] = [];

function place(entry: Anchored, kind: WorldPlace["kind"]): void {
  if (!entry.map_anchor) return;
  const slug = slugOf(entry.id);
  if (places[slug]) {
    problems.push(`"${slug}" is both ${places[slug]!.id} and ${entry.id}; the world map is one namespace.`);
    return;
  }
  const { x, y } = entry.map_anchor;
  if (x < 0 || x > 1000 || y < 0 || y > 1000) {
    problems.push(`${entry.id} map_anchor (${String(x)}, ${String(y)}) is outside the 1000×1000 frame.`);
    return;
  }
  places[slug] = {
    id: entry.id,
    title: entry.title,
    kind,
    anchor: { x, y },
    parent: entry.parent_biome ? slugOf(entry.parent_biome) : null,
  };
}

for (const biome of (registry.byTaxonomy.get("biome") ?? []) as unknown as Anchored[]) {
  place(biome, "biome");
}
for (const location of (registry.byTaxonomy.get("location") ?? []) as unknown as Anchored[]) {
  place(location, "location");
}
for (const entry of Object.values(places)) {
  if (entry.parent !== null && !places[entry.parent]) {
    // A settlement whose biome is not on the map is still on the map itself;
    // it just has no country to name. Drop the pointer rather than the place.
    entry.parent = null;
  }
}

if (problems.length > 0) {
  console.error("canon:world — refusing to write content/world.json:");
  for (const problem of problems) console.error(`  - ${problem}`);
  process.exit(1);
}

if (!fs.existsSync(IMAGE)) {
  console.error(`canon:world — ${path.relative(ROOT, IMAGE)} is missing; the map is the painting.`);
  process.exit(1);
}

const sorted = Object.fromEntries(Object.entries(places).sort(([a], [b]) => a.localeCompare(b)));
const doc: { $comment: string } & WorldMap = {
  $comment:
    "GENERATED by `npm run canon:world` from canon/biomes.yaml and canon/locations.yaml. Do not edit. " +
    "Anchors are canon's normalized 1000×1000 label anchors (geography.yaml, world_metadata); " +
    "the image is the realm painting, served from /assets.",
  title: "The Realm of Red Sky",
  image: { src: "/assets/world/realm_of_red_sky.webp", ...webpSize(IMAGE) },
  places: sorted,
};

fs.writeFileSync(OUT, `${JSON.stringify(doc, null, 2)}\n`);
console.log(`canon:world — wrote ${path.relative(ROOT, OUT)} (${String(Object.keys(sorted).length)} places)`);
