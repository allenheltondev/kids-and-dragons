"""
Kids & Dragons - the ground colour of every backdrop a hero stands on, for the colour tests.

docs/hero-looks.md section 7.1: every starter colour must stand out from every backdrop's ground
colour by an OKLab distance of at least 0.10, so a hero never disappears into the scenery. The
client's palette test (packages/client/src/world/coat-palette.test.ts) cannot decode a WebP, so
this measures them once and writes the numbers it reads:

    packages/client/src/world/coat-backdrops.fixture.json

The ground is the band a hero's feet and body stand in: the bottom 30% of the canvas (the
story stage's ground line is at 0.88 of its height; the camp's lanes sit between 0.6 and 0.95),
averaged in linear light and written back as sRGB hex. Every biome background
(assets/biomes/<id>/bg.webp) and every camp backdrop (manifest camp.backdrops) is measured.

Run it again when a backdrop is added or repainted: the test fails while a biome the manifest
lists is missing from the fixture.

    python3 tools/art/backdrop-grounds.py

Requires: Pillow, numpy
"""

from __future__ import annotations

import json
import os

import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "packages", "client", "src", "world", "coat-backdrops.fixture.json")
BAND = 0.30


def ground_hex(path: str) -> str:
    im = Image.open(path).convert("RGB")
    w, h = im.size
    band = im.crop((0, int(h * (1 - BAND)), w, h)).resize((256, max(1, int(256 * BAND * h / w))), Image.BILINEAR)
    rgb = np.asarray(band, dtype=np.float64) / 255.0
    lin = np.where(rgb <= 0.04045, rgb / 12.92, ((rgb + 0.055) / 1.055) ** 2.4).reshape(-1, 3).mean(axis=0)
    srgb = np.where(lin <= 0.0031308, lin * 12.92, 1.055 * np.power(lin, 1 / 2.4) - 0.055)
    return "#" + "".join(f"{int(round(c * 255)):02X}" for c in np.clip(srgb, 0, 1))


def main() -> None:
    mf = json.load(open(os.path.join(ROOT, "assets", "manifest.json"), encoding="utf-8"))
    grounds: dict[str, str] = {}
    biomes = os.path.join(ROOT, "assets", "biomes")
    for biome in sorted(os.listdir(biomes)):
        bg = os.path.join(biomes, biome, "bg.webp")
        if os.path.isfile(bg):
            grounds[f"biomes/{biome}"] = ground_hex(bg)
    for entry in sorted(mf.get("camp", {}).get("backdrops", []), key=lambda e: e["family"]):
        p = os.path.join(ROOT, "assets", *entry["path"].split("/"))
        if os.path.isfile(p):
            grounds[f"camp/{entry['family']}"] = ground_hex(p)
    out = {
        "$comment": "Generated by tools/art/backdrop-grounds.py: the mean colour of the bottom 30% of every backdrop a hero stands on, for the starter colours' backdrop test (docs/hero-looks.md section 7.1). Do not edit by hand; run the script again when a backdrop changes.",
        "grounds": grounds,
    }
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(out, f, indent=2)
        f.write("\n")
    print(f"wrote {len(grounds)} grounds to {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
