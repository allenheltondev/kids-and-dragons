#!/usr/bin/env python3
"""
The camp's painted footprints (docs/camp.md §8.3, docs/briefs/camp.md; #620, #623).

Every camp painting that stands on the ground (a frame piece, a kit, a tent, a crew piece,
the souvenir line) is a cutout on the 1024 figure canvas, and the camp draws it so its
*painted* height is its `heightCm` (camp.ts `fitCanvas`). How wide it then is, and how far
its paint sits off the canvas's middle, is the painting's own business: a crew banner's pole
stands at the ground contact and its flag flies off to the right. The layout's boxes
(packages/client/src/world/camp-boxes.ts) and both renderers read that footprint from the
table this writes, `packages/client/src/world/camp-paint.json`, so the overlap tests judge
what is drawn rather than a guess.

A crew piece's pennant (its rippling moving part, on the same canvas registration) is measured
too: the layout keeps all of it clear, however far below the piece's top half its streamers hang.

A footprint is the opaque bounds (alpha over 64, as actor-art.ts `measurePaint` counts it)
in canvas px, `box`: [left, top, right, bottom), right and bottom exclusive; and `bands`, the
same painting cut into BANDS equal slices of its painted height, top to bottom, each slice's
opaque [left, right) or null where it is empty. A banner's flag is wide only in its top
slices, so a short piece may stand under it; a tent's guy ropes are wide only at its foot.

Usage:
    python3 tools/art/camp-paint.py           # rewrite the table from the paintings
    python3 tools/art/camp-paint.py --check   # exit 1 if the table is stale (art:verify runs this)

Requires: Pillow
"""

from __future__ import annotations

import json
import math
import os
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
TABLE_REL = os.path.join("packages", "client", "src", "world", "camp-paint.json")
TABLE = os.path.join(ROOT, TABLE_REL)
ALPHA_OVER = 64
BANDS = 6
COMMENT = (
    "Generated by `npm run art:camp-paint` (tools/art/camp-paint.py) from the paintings: each grounded camp "
    "painting's (and each crew piece's pennant's) opaque bounds on its 1024 canvas (box: [left, top, right, bottom) px, alpha over 64), and the "
    "opaque [left, right) of each of `bands` equal slices of its painted height, top to bottom (null: empty). "
    "Do not edit; art:verify and tools/art/camp-art.test.ts fail when it is stale."
)


def grounded_paths(mf: dict) -> list[str]:
    """Every camp painting that stands on the ground, as the manifest declares it."""
    camp = mf.get("camp") or {}
    paths: set[str] = set()
    for frame in camp.get("frames", []):
        paths.update(p["path"] for p in frame.get("pieces", []))
    paths.update(k["path"] for k in camp.get("kitStyles", []))
    paths.update(p["path"] for p in camp.get("crewPieces", []))
    paths.update(t["path"] for t in camp.get("tentStyles", []))
    if camp.get("souvenirDisplay"):
        paths.add(camp["souvenirDisplay"]["path"])
    return sorted(paths)


def pennant_paths(mf: dict) -> list[str]:
    """Every pennant (a crew piece's rippling moving part), whose streamers the layout keeps clear (camp-boxes.ts `pieceKeepTop`)."""
    camp = mf.get("camp") or {}
    return sorted({part["path"] for p in camp.get("crewPieces", []) for part in p.get("movingParts", []) if part.get("motion") == "ripple"})


def footprint(path: str) -> dict | None:
    with Image.open(path) as im:
        alpha = im.convert("RGBA").getchannel("A").point(lambda v: 255 if v > ALPHA_OVER else 0)
    box = alpha.getbbox()
    if not box:
        return None
    left, top, right, bottom = box
    bands: list[list[int] | None] = []
    for i in range(BANDS):
        # Rounded half up, as the client's Math.round cuts the same slices (camp-paint.ts).
        y0 = top + math.floor(i * (bottom - top) / BANDS + 0.5)
        y1 = top + math.floor((i + 1) * (bottom - top) / BANDS + 0.5)
        slice_box = alpha.crop((0, y0, alpha.width, y1)).getbbox()
        bands.append([slice_box[0], slice_box[2]] if slice_box else None)
    return {"box": list(box), "bands": bands}


def measure(root: str = ROOT) -> dict:
    with open(os.path.join(root, "assets", "manifest.json"), encoding="utf-8") as f:
        mf = json.load(f)
    paint: dict[str, dict] = {}
    for rel in grounded_paths(mf) + pennant_paths(mf):
        path = os.path.join(root, "assets", rel)
        if not os.path.isfile(path):
            continue  # owed: the camp draws a stand-in at the declared size
        found = footprint(path)
        if found:
            paint[rel] = found
    return {"$comment": COMMENT, "canvas": 1024, "alphaOver": ALPHA_OVER, "bands": BANDS, "paint": paint}


def render(table: dict) -> str:
    lines = [
        "{",
        f'  "$comment": {json.dumps(table["$comment"])},',
        f'  "canvas": {table["canvas"]},',
        f'  "alphaOver": {table["alphaOver"]},',
        f'  "bands": {table["bands"]},',
        '  "paint": {',
    ]
    entries = sorted(table["paint"].items())
    for i, (rel, found) in enumerate(entries):
        bands = ", ".join("null" if band is None else f"[{band[0]}, {band[1]}]" for band in found["bands"])
        box = ", ".join(str(v) for v in found["box"])
        lines.append(f'    {json.dumps(rel)}: {{ "box": [{box}], "bands": [{bands}] }}{"," if i < len(entries) - 1 else ""}')
    lines += ["  }", "}", ""]
    return "\n".join(lines)


def stale(root: str = ROOT) -> list[str]:
    """What the checked-in table gets wrong against the paintings on disk (empty: up to date)."""
    want = measure(root)
    try:
        with open(os.path.join(root, TABLE_REL), encoding="utf-8") as f:
            have_table = json.load(f)
    except FileNotFoundError:
        return ["the table is missing"]
    if have_table.get("bands") != want["bands"]:
        return [f"bands {have_table.get('bands')}, want {want['bands']}"]
    have = have_table.get("paint", {})
    problems = [f"{rel}: table {have.get(rel)}, painting {found}" for rel, found in want["paint"].items() if have.get(rel) != found]
    problems += [f"{rel}: in the table, no painting" for rel in have if rel not in want["paint"]]
    return problems


def main() -> int:
    if "--check" in sys.argv:
        problems = stale()
        for problem in problems:
            print(f"stale camp paint table: {problem}")
        if problems:
            print("run `npm run art:camp-paint` and commit packages/client/src/world/camp-paint.json")
            return 1
        print("camp paint table up to date")
        return 0
    table = measure()
    with open(TABLE, "w", encoding="utf-8", newline="\n") as f:
        f.write(render(table))
    print(f"wrote {TABLE_REL}: {len(table['paint'])} paintings")
    return 0


if __name__ == "__main__":
    sys.exit(main())
