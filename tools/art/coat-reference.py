"""
Kids & Dragons - the colour swap's reference sheet (docs/hero-looks.md section 5.2, section 12).

No hero has a shipped coat mask yet (#667, #668), so the reference is a small painting made
here, in code, with the parts that matter to the swap: a shaded body (lightness steps to keep),
a darker mane beside it, a dark outline, a transparent ground, and an RGB mask (owner,
2026-11-07): red the body (her main part, with a soft edge), green the mane (her accent part,
its soft edge overlapping the body's), blue the whole figure (the painting's alpha). Two of
them: a lavender coat (chroma to keep, as a unicorn's) and a white one (near-grey: the
colour's chroma is taken flat). Each is tinted, by coat.py, the review sheet's tinter:

    tinted   the main part alone, by the single-mask `tint` (the red channel), to four test
             colours: one light, one dark, one too saturated for sRGB at its lightness (the
             gamut case), and one grey; the outline and the mane must not change
    parts    both parts at once, each its own colour (`tint_parts`), and each part alone
    gilded   the whole figure to a gold (`gild`), her colours ignored

    python3 tools/art/coat-reference.py            # write the reference
    python3 tools/art/coat-reference.py --check    # regenerate and compare; exit 1 if it moved

writes

    tools/art/fixtures/coat-reference.json   the paintings, the masks and every tinted result,
                                             as base64 RGBA (the masks RGB; the client's tinter is held to it:
                                             packages/client/src/world/hero-coat.test.ts)
    tools/art/fixtures/coat-reference.png    the same, as a sheet a person can look at

Requires: Pillow, numpy
"""

from __future__ import annotations

import base64
import json
import os
import sys

import numpy as np
from PIL import Image, ImageDraw, ImageFilter

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import coat  # noqa: E402

OUT_JSON = os.path.join(HERE, "fixtures", "coat-reference.json")
OUT_PNG = os.path.join(HERE, "fixtures", "coat-reference.png")
SIZE = 32
COATS = {"light": "#F4F1EA", "dark": "#20134E", "saturated": "#00FF40", "grey": "#808080"}
# Both parts (main, accent); None leaves a part as painted.
PARTS = {"dusk": ("#F4D986", "#3E1D6B"), "sea": ("#77E2C5", "#F4D986"), "main only": ("#3E6ADF", None), "accent only": (None, "#F4F1EA")}
# Gilded specials (section 5.5): the whole figure to one gold.
GILDED = {"gold": "#E2B13C", "pale gold": "#F2DE9A"}
BODIES = {"lavender": (226, 205, 236), "white": (244, 243, 240)}


def painting(body: tuple[int, int, int]) -> tuple[np.ndarray, np.ndarray]:
    """A small hero: a shaded body ellipse, a mane, an outline. And its RGB mask: the body's
    soft mask in red, the mane's in green, the figure (its alpha) in blue."""
    s = SIZE
    yy, xx = np.mgrid[0:s, 0:s].astype(np.float64)
    rgba = np.zeros((s, s, 4), dtype=np.float64)
    inside = ((xx - 16) / 12) ** 2 + ((yy - 18) / 10) ** 2 <= 1.0
    # shading: lit from the top left, darker to the bottom right, with a highlight
    shade = 1.0 - 0.35 * ((xx + yy) / (2 * s)) + 0.15 * np.exp(-(((xx - 11) ** 2 + (yy - 13) ** 2) / 12))
    for c in range(3):
        rgba[..., c] = np.where(inside, np.clip(body[c] * shade, 0, 255), 0)
    rgba[..., 3] = np.where(inside, 255, 0)
    # a purple mane over the top of the body, which the mask leaves alone
    mane = inside & (yy < 12)
    rgba[mane, :3] = (133, 58, 133)
    # an outline ring
    edge = inside & ~(((xx - 16) / 11) ** 2 + ((yy - 18) / 9) ** 2 <= 1.0)
    rgba[edge, :3] = (59, 29, 54)
    rgba = rgba.round().astype(np.uint8)

    m = Image.new("L", (s, s))
    ImageDraw.Draw(m).ellipse((6, 12, 26, 26), fill=255)
    m = m.filter(ImageFilter.GaussianBlur(1.2))
    mask = np.asarray(m, dtype=np.float64)
    main = np.where(mane | edge | ~inside, 0, mask)
    # the mane, softened a little into the body below it, so the two parts' edges overlap
    a = Image.fromarray((mane * 255).astype(np.uint8), "L").filter(ImageFilter.GaussianBlur(0.8))
    accent = np.where(edge | ~inside, 0, np.asarray(a, dtype=np.float64))
    figure = rgba[..., 3].astype(np.float64)
    rgb = np.stack([main, accent, figure], axis=-1)
    return rgba, rgb.round().astype(np.uint8)


def b64(a: np.ndarray) -> str:
    return base64.b64encode(np.ascontiguousarray(a).tobytes()).decode("ascii")


def build() -> dict:
    out = {
        "$comment": "Generated by tools/art/coat-reference.py from tools/art/coat.py tint (docs/hero-looks.md section 5.2). Do not edit; run the script again if the swap changes on purpose.",
        "size": SIZE,
        "coats": COATS,
        "parts": {k: {"main": main, "accent": accent} for k, (main, accent) in PARTS.items()},
        "gilded": GILDED,
        "paintings": {},
    }
    for name, body in BODIES.items():
        rgba, mask = painting(body)
        tinted = {k: b64(coat.tint(rgba, mask[..., 0], hexv)) for k, hexv in COATS.items()}
        parts = {k: b64(coat.tint_parts(rgba, mask, main, accent)) for k, (main, accent) in PARTS.items()}
        gilded = {k: b64(coat.gild(rgba, mask, hexv)) for k, hexv in GILDED.items()}
        out["paintings"][name] = {"rgba": b64(rgba), "mask": b64(mask), "tinted": tinted, "parts": parts, "gilded": gilded}
    return out


def sheet(ref: dict) -> Image.Image:
    s = ref["size"]
    rows = list(ref["paintings"].items())
    cols = ["painting", "mask", *ref["coats"].keys(), *ref["parts"].keys(), *ref["gilded"].keys()]
    scale = 4
    im = Image.new("RGBA", (len(cols) * s * scale, len(rows) * s * scale), (40, 44, 60, 255))
    for r, (_, p) in enumerate(rows):
        cells = [p["rgba"], None, *p["tinted"].values(), *p["parts"].values(), *p["gilded"].values()]
        for c, cell in enumerate(cells):
            if cell is None:
                m = np.frombuffer(base64.b64decode(p["mask"]), dtype=np.uint8).reshape(s, s, 3)
                tile = Image.fromarray(m, "RGB").convert("RGBA")
            else:
                tile = Image.fromarray(np.frombuffer(base64.b64decode(cell), dtype=np.uint8).reshape(s, s, 4), "RGBA")
            tile = tile.resize((s * scale, s * scale), Image.NEAREST)
            im.alpha_composite(tile, (c * s * scale, r * s * scale))
    return im


def main() -> int:
    ref = build()
    if "--check" in sys.argv:
        with open(OUT_JSON, encoding="utf-8") as f:
            committed = json.load(f)
        if committed != ref:
            print("coat-reference.json no longer matches coat.py tint: run tools/art/coat-reference.py", file=sys.stderr)
            return 1
        print("coat reference unchanged")
        return 0
    os.makedirs(os.path.dirname(OUT_JSON), exist_ok=True)
    with open(OUT_JSON, "w", encoding="utf-8") as f:
        json.dump(ref, f, indent=1)
        f.write("\n")
    sheet(ref).save(OUT_PNG, optimize=True)
    print(f"wrote {os.path.relpath(OUT_JSON)} and {os.path.relpath(OUT_PNG)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
