/**
 * `npm run art:figures` — write the stage's height table (#362).
 *
 * Canon says how tall everything is (`height_cm`, `stance` in canon/*.yaml) and
 * the manifest says it for the figures canon does not own (`castFigures`,
 * `stageFigures`). The client may not import canon: Zod would land in the game
 * bundle for a table of numbers. So this projects both into one small module,
 * packages/client/src/world/figure-sizes.ts, keyed by the figure path a chapter
 * casts (`entities/selkie`, `cast/pib`, `characters/unicorn`).
 *
 * The output is committed, and figure-sizes.test.ts fails when it is stale, so
 * a height edited in canon cannot quietly fail to reach the screen.
 */

import fs from "node:fs";
import path from "node:path";
import { loadCanon } from "@kad/canon";

const ROOT = path.resolve(import.meta.dirname, "..", "..");
export const OUTPUT = path.join(ROOT, "packages", "client", "src", "world", "figure-sizes.ts");

type Stance = "standing" | "hovering" | "flying" | "swimming";
export interface FigureSize {
  heightCm: number;
  stance: Stance;
  /** Where the number came from, for the test's failure messages. */
  source: string;
}

interface Sized {
  id: string;
  asset_id?: string;
  height_cm?: number;
  stance?: Stance;
}

interface ManifestFigure {
  id: string;
  heightCm?: number;
  stance?: Stance;
}

type Overflow = "top" | "right";

function readManifest(root: string) {
  return JSON.parse(fs.readFileSync(path.join(root, "assets", "manifest.json"), "utf8")) as {
    castFigures: ManifestFigure[];
    stageFigures?: ManifestFigure[];
    figureOverflow?: Record<string, Overflow>;
  };
}

/** The manifest's per-figure overflow overrides (`figureOverflow`). */
export function figureOverflow(root = ROOT): Record<string, Overflow> {
  return readManifest(root).figureOverflow ?? {};
}

export function figureSizes(root = ROOT): Map<string, FigureSize> {
  const registry = loadCanon(path.join(root, "canon"));
  const manifest = readManifest(root);
  const out = new Map<string, FigureSize>();
  const put = (key: string, entity: { height_cm?: number; stance?: Stance } | ManifestFigure, source: string) => {
    const heightCm = "heightCm" in entity ? entity.heightCm : (entity as Sized).height_cm;
    if (heightCm === undefined || entity.stance === undefined) return;
    out.set(key, { heightCm, stance: entity.stance, source });
  };

  const inTaxonomy = (...taxonomies: string[]) =>
    ([...registry.byId.values()] as Sized[]).filter((e) => taxonomies.includes(registry.taxonomyOf.get(e.id) ?? ""));
  const slug = (id: string) => id.slice(id.indexOf(".") + 1);

  for (const species of inTaxonomy("species")) {
    put(`characters/${species.asset_id ?? slug(species.id)}`, species, species.id);
  }

  // Entity art: a creature or people by its asset_id (or its slug, where canon
  // gives none), else an individual drawn as an entity (Pib), else the
  // manifest's stage-only animals. The Skywardens' group picture is never
  // drawn whole (world/cast.ts ENSEMBLES), so it needs no height.
  const kinds = inTaxonomy("creature", "people");
  const individuals = inTaxonomy("individual");
  const stageOnly = new Map((manifest.stageFigures ?? []).map((f) => [f.id, f]));
  const entityDirs = fs.readdirSync(path.join(root, "assets", "entities")).filter((dir) =>
    fs.existsSync(path.join(root, "assets", "entities", dir, "assembled.png")),
  );
  for (const dir of entityDirs.sort()) {
    const kind = kinds.find((e) => e.asset_id === dir) ?? kinds.find((e) => !e.asset_id && slug(e.id) === dir);
    const individual = individuals.find((e) => slug(e.id) === dir);
    const animal = stageOnly.get(dir);
    if (kind) put(`entities/${dir}`, kind, kind.id);
    else if (individual) put(`entities/${dir}`, individual, individual.id);
    else if (animal) put(`entities/${dir}`, animal, "assets/manifest.json stageFigures");
  }

  for (const figure of manifest.castFigures) put(`cast/${figure.id}`, figure, "assets/manifest.json castFigures");
  return out;
}

export function renderFigureSizes(sizes = figureSizes(), overflow = figureOverflow()): string {
  const rows = [...sizes.entries()]
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([key, size]) => `  ${JSON.stringify(key)}: [${size.heightCm}, ${JSON.stringify(size.stance)}],`);
  return [
    "/**",
    " * How tall each figure stands, in centimeters, and how it occupies a scene (#362).",
    " *",
    " * GENERATED by `npm run art:figures` from canon/*.yaml (`height_cm`, `stance`)",
    " * and assets/manifest.json (`castFigures`, `stageFigures`, `figureOverflow`). Do not edit: change",
    " * the source and regenerate. tools/art/figure-sizes.test.ts fails while stale.",
    " *",
    " * Centimeters are data. They are never shown to a player.",
    " */",
    "",
    'import type { CastStance } from "@kad/shared";',
    "",
    "export const FIGURE_SIZES: Readonly<Record<string, readonly [heightCm: number, stance: CastStance]>> = {",
    ...rows,
    "};",
    "",
    "/**",
    " * How a figure too big for the story stage overflows it, where the manifest",
    " * says (`figureOverflow`); any other figure goes by its painting's shape.",
    " */",
    'export const FIGURE_OVERFLOW: Readonly<Record<string, "top" | "right">> = {',
    ...Object.entries(overflow)
      .sort(([a], [b]) => (a < b ? -1 : 1))
      .map(([key, way]) => `  ${JSON.stringify(key)}: ${JSON.stringify(way)},`),
    "};",
    "",
  ].join("\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) {
  fs.writeFileSync(OUTPUT, renderFigureSizes());
  console.log(`wrote ${path.relative(ROOT, OUTPUT)}`);
}
